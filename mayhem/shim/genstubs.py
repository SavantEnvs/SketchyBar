#!/usr/bin/env python3
"""Generate no-op definitions for the Apple framework functions SketchyBar calls.

Reads one-line prototypes from mayhem/shim/include/apple_shim.h (between the BEGIN/END
PROTOTYPES markers) and the `extern` private-framework prototypes from upstream's
src/misc/extern.h, and writes a C file defining each one as "return a zeroed value".
Names already defined by hand in mayhem/shim/sb_env.c are skipped.

usage: genstubs.py <repo root> <out.c>
"""
import re
import sys
from pathlib import Path

root = Path(sys.argv[1])
out = Path(sys.argv[2])
proto_re = re.compile(r'^\s*(?:extern\s+)?([A-Za-z_][\w\s\*]*?[\s\*])([A-Za-z_]\w*)\s*\((.*)\)\s*;\s*$')

lines = []
shim = (root / "mayhem/shim/include/apple_shim.h").read_text().splitlines()
inside = False
for l in shim:
    if "BEGIN PROTOTYPES" in l:
        inside = True
        continue
    if "END PROTOTYPES" in l:
        inside = False
    if inside:
        lines.append(l)
for hdr in ["src/misc/extern.h"]:
    p = root / hdr
    if p.exists():
        lines += [l for l in p.read_text().splitlines() if l.lstrip().startswith("extern") and "(" in l]

handwritten = set(re.findall(r'^\S[^\n(]*?\b(\w+)\s*\(', (root / "mayhem/shim/sb_env.c").read_text(), re.M))

seen = set()
body = ["/* GENERATED by mayhem/shim/genstubs.py — do not edit. */",
        '#include "misc/helpers.h"', ""]
for l in lines:
    m = proto_re.match(l)
    if not m:
        continue
    ret, name, args = m.group(1).strip(), m.group(2), m.group(3).strip()
    if name in seen or name in handwritten:
        continue
    seen.add(name)
    # name every parameter so the definition is valid C
    params = []
    if args and args != "void":
        for i, a in enumerate(args.split(",")):
            a = a.strip()
            if a == "...":
                params.append(a)
                continue
            a = re.sub(r'\b\w+\s*$', '', a) if re.search(r'[\w\*]\s+\**\w+\s*$', a) and not a.endswith("*") else a
            params.append(f"{a.strip()} p{i}")
    sig = f"{ret} {name}({', '.join(params) if params else 'void'})"
    if ret == "void":
        body.append(f"{sig} {{ }}")
    else:
        body.append(f"{sig} {{ {ret} r; memset(&r, 0, sizeof(r)); return r; }}")
out.parent.mkdir(parents=True, exist_ok=True)
out.write_text("\n".join(body) + "\n")
